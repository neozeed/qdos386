#!/usr/bin/env python3
"""Generate the R11D libm test table (sdk/examples/r11d/tables/mathx.h).

The reference is Python's math module (the platform libm, glibc, which is
correctly rounded for these functions in nearly all cases).  Each row is:
function id, x and y as IEEE bit patterns, and the expected result.  Fixed seed,
so the output is reproducible:
    python3 scripts/r11d-tables.py sdk/examples/r11d/tables
"""
import math, random, struct, sys, os

OUT = sys.argv[1] if len(sys.argv) > 1 else "sdk/examples/r11d/tables"
os.makedirs(OUT, exist_ok=True)
rng = random.Random(1104)

# function ids, used by the C test
FN = {"exp": 0, "log": 1, "log10": 2, "sin": 3, "cos": 4, "tan": 5, "asin": 6,
      "acos": 7, "atan": 8, "atan2": 9, "sinh": 10, "cosh": 11, "tanh": 12, "fmod": 13}

def bits(x):
    b = struct.unpack("<Q", struct.pack("<d", x))[0]
    return "0x%08xUL, 0x%08xUL" % (b & 0xffffffff, b >> 32)

rows = []
def add(name, x, y, r):
    rows.append((FN[name], x, y, r))

for _ in range(40):
    x = rng.uniform(-700.0, 700.0)
    add("exp", x, 0.0, math.exp(x))
for x in [0.0, 1.0, -1.0, 0.5, 1e-300, 1e-10, 709.0, -745.0, -700.0]:
    add("exp", x, 0.0, math.exp(x) if math.exp(x) != 0.0 or x < -700 else 0.0)
for _ in range(40):
    x = 10.0 ** rng.uniform(-300.0, 300.0)
    add("log", x, 0.0, math.log(x))
    add("log10", x, 0.0, math.log10(x))
for x in [1.0, 2.0, 10.0, 0.1, 0.5]:
    add("log", x, 0.0, math.log(x))
    add("log10", x, 0.0, math.log10(x))
for _ in range(40):
    x = rng.uniform(-1.0e4, 1.0e4)
    add("sin", x, 0.0, math.sin(x))
    add("cos", x, 0.0, math.cos(x))
    t = rng.uniform(-1.5, 1.5)
    add("tan", t, 0.0, math.tan(t))
for x in [0.0, -0.0, 1e-8, math.pi, math.pi / 2, math.pi / 4, 1.0]:
    add("sin", x, 0.0, math.sin(x))
    add("cos", x, 0.0, math.cos(x))
for _ in range(30):
    x = rng.uniform(-1.0, 1.0)
    add("asin", x, 0.0, math.asin(x))
    add("acos", x, 0.0, math.acos(x))
for _ in range(30):
    x = rng.uniform(-100.0, 100.0)
    add("atan", x, 0.0, math.atan(x))
    y = rng.uniform(-50.0, 50.0)
    xx = rng.uniform(-50.0, 50.0)
    if xx != 0.0:
        add("atan2", y, xx, math.atan2(y, xx))
for _ in range(30):
    x = rng.uniform(-40.0, 40.0)
    add("sinh", x, 0.0, math.sinh(x))
    add("cosh", x, 0.0, math.cosh(x))
    add("tanh", x, 0.0, math.tanh(x))
for x in [1e-9, -1e-9, 0.0]:
    add("sinh", x, 0.0, math.sinh(x))
    add("tanh", x, 0.0, math.tanh(x))
for _ in range(40):
    x = rng.uniform(-1000.0, 1000.0)
    y = rng.uniform(0.5, 100.0) * rng.choice([1.0, -1.0])
    add("fmod", x, y, math.fmod(x, y))

with open(os.path.join(OUT, "mathx.h"), "w") as f:
    f.write("/* mathx.h: generated by scripts/r11d-tables.py (Python math as the reference). Do not edit. */\n")
    f.write("struct mathx_row { int fn; unsigned long xlo, xhi, ylo, yhi, rlo, rhi; };\n")
    f.write("static const struct mathx_row mathx_rows[] = {\n")
    for fn, x, y, r in rows:
        f.write("\t{ %d, %s, %s, %s },\n" % (fn, bits(x), bits(y), bits(r)))
    f.write("};\n")
    f.write("#define NMATHX %d\n" % len(rows))
print("rows", len(rows))
