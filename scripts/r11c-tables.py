#!/usr/bin/env python3
"""Generate the R11C test tables (C headers) from Python's exact conversions.

Python's float(), '%' formatting and math functions are the reference: float()
and '%f/%e/%g' are correctly rounded (round-half-even on the exact value), the
same rule the C89 library is required to follow in the C locale.  The tables
are fixed-seed, so the output is reproducible:

    python3 scripts/r11c-tables.py sdk/examples/r11c/tables

Each row carries the expected IEEE bit pattern as two 32-bit words (lo, hi).
"""
import math, random, re, struct, sys, os

OUT = sys.argv[1] if len(sys.argv) > 1 else "sdk/examples/r11c/tables"
os.makedirs(OUT, exist_ok=True)
rng = random.Random(1103)

def bits(x):
    b = struct.unpack("<Q", struct.pack("<d", x))[0]
    return b & 0xffffffff, b >> 32

DBL_MAX = 1.7976931348623157e308
DIGITS = re.compile(r"[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?")

def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def c_bits(x):
    lo, hi = bits(x)
    return "0x%08xUL, 0x%08xUL" % (lo, hi)

# ---- strtod table --------------------------------------------------------
def c89_parse(s):
    """Return (value, end offset, errno_expected) by the C89 grammar."""
    m = re.match(r"[ \t\n\r\f\v]*", s)
    i = m.end()
    j = i
    if j < len(s) and s[j] in "+-":
        j += 1
    k = j
    while k < len(s) and s[k].isdigit():
        k += 1
    nint = k - j
    nfrac = 0
    if k < len(s) and s[k] == ".":
        k2 = k + 1
        while k2 < len(s) and s[k2].isdigit():
            k2 += 1
        nfrac = k2 - (k + 1)
        k = k2
    if nint + nfrac == 0:
        return 0.0, 0, 0
    end = k
    if k < len(s) and s[k] in "eE":
        m2 = re.match(r"[eE][+-]?\d+", s[k:])
        if m2:
            end = k + m2.end()
    txt = s[i:end]
    try:
        v = float(txt)
    except (ValueError, OverflowError):
        v = math.inf
    err = 0
    if math.isinf(v):
        v = math.copysign(DBL_MAX, v)
        err = 34
    elif v == 0.0 and re.search(r"[1-9]", re.split(r"[eE]", txt)[0]):
        err = 34
    elif v != 0.0 and abs(v) < 2.2250738585072014e-308:
        err = 34
    return v, end, err

parse_cases = []
fixed = [
    "0", "-0", "+0.0", " 1.5", "\t\n-2.5e3xyz", "1e", "1e+", "1.", ".5", ".", "-", "",
    "0x1A", "1e400", "-1e400", "1e-400", "4.9406564584124654e-324", "2.2250738585072011e-308",
    "2.2250738585072014e-308", "1.7976931348623157e308", "1.7976931348623158e308",
    "1.797693134862315807e308", "9007199254740993", "9007199254740995",
    "0.1", "0.2", "0.3", "2.5e-310", "123456789012345678901234567890",
    "1.00000000000000011102230246251565404236316680908203125",
    "1.00000000000000033306690738754696212708950042724609375",
    "1" + "0" * 400, "0." + "0" * 400 + "1", "-" + "7" * 900, "3." + "1" * 800 + "e-400",
    "2.5", "3.5", "0.5e1", "12e-1", "  \n 42", "1e0003", "1e-0004", "5e+00308",
]
for s in fixed:
    parse_cases.append(s)
for _ in range(260):
    nd = rng.randint(1, 30)
    digs = "".join(rng.choice("0123456789") for _ in range(nd))
    if rng.random() < 0.5:
        p = rng.randint(0, nd)
        digs = digs[:p] + "." + digs[p:]
    if digs.startswith("."):
        digs = "0" + digs
    e = rng.randint(-340, 320) if rng.random() < 0.7 else rng.randint(-30, 30)
    sign = rng.choice(["", "", "-", "+"])
    ex = rng.choice(["e", "E"]) + ("%d" % e) if rng.random() < 0.8 else ""
    parse_cases.append(sign + digs + ex + rng.choice(["", "", " x", "z"]))

with open(os.path.join(OUT, "parse.h"), "w") as f:
    f.write("/* parse.h: generated by scripts/r11c-tables.py. Do not edit. */\n")
    f.write("struct parse_case { const char *s; unsigned long lo, hi; int end; int err; };\n")
    f.write("static const struct parse_case parse_cases[] = {\n")
    for s in parse_cases:
        v, end, err = c89_parse(s)
        lo, hi = bits(v)
        f.write("\t{ %s, 0x%08xUL, 0x%08xUL, %d, %d },\n" % (c_str(s), lo, hi, end, err))
    f.write("};\n")
    f.write("#define NPARSE %d\n" % len(parse_cases))
print("parse cases:", len(parse_cases))

# ---- printf table --------------------------------------------------------
values = [0.0, -0.0, 0.5, 1.5, 2.5, 0.125, 1e22, 1e-7, 123456.5, 5e-324,
          2.2250738585072014e-308, DBL_MAX, 1e308, 0.1, 1.0 / 3.0, 2.0 / 3.0,
          100.0, 99.99, 9.9999999, 0.000123456, 1e-5, 1e15, 9007199254740993.0]
for _ in range(60):
    e = rng.randint(-300, 300)
    m = rng.random()
    v = m * (10.0 ** e)
    if rng.random() < 0.3:
        v = -v
    values.append(v)
specs = ["%f", "%.0f", "%.2f", "%.10f", "%e", "%.0e", "%.3E", "%g", "%G", "%.0g",
         "%.10g", "%#g", "%#.0f", "%+.3f", "% f", "%12.4f", "%-12.4e|", "%012.3f",
         "%.20f", "%.60e", "%.17g", "%+e", "%#.0e", "%010.2e", "%-9g|", "%.400f"]
fmt_cases = []
for v in values:
    for sp in specs:
        if sp == "%.400f" and abs(v) > 1e100:
            continue
        exp = sp % v
        if sp.startswith("%-") or sp.endswith("|"):
            pass
        fmt_cases.append((sp, v, exp))
rng.shuffle(fmt_cases)
fmt_cases = fmt_cases[:900]
with open(os.path.join(OUT, "printf.h"), "w") as f:
    f.write("/* printf.h: generated by scripts/r11c-tables.py. Do not edit. */\n")
    f.write("struct fmt_case { const char *spec; unsigned long lo, hi; const char *want; };\n")
    f.write("static const struct fmt_case fmt_cases[] = {\n")
    for sp, v, exp in fmt_cases:
        lo, hi = bits(v)
        f.write("\t{ %s, 0x%08xUL, 0x%08xUL, %s },\n" % (c_str(sp), lo, hi, c_str(exp)))
    f.write("};\n")
    f.write("#define NFMT %d\n" % len(fmt_cases))
print("format cases:", len(fmt_cases), "max length", max(len(e) for _, _, e in fmt_cases))

# ---- libm table ----------------------------------------------------------
xs = [0.0, -0.0, 1.0, -1.0, 0.5, -0.5, 2.5, -2.5, 3.75, -3.75, 1e-300, 1e300,
      5e-324, 2.2250738585072014e-308, 4503599627370497.5, 4503599627370496.0,
      -4503599627370497.5, 123.456, -123.456, 1024.0, 0.75]
for _ in range(120):
    e = rng.randint(-60, 60)
    v = rng.random() * (2.0 ** e)
    if rng.random() < 0.4:
        v = -v
    xs.append(v)
math_rows = []
for x in xs:
    fl = float(math.floor(x)) if math.isfinite(x) else x
    ce = float(math.ceil(x))
    fr, ip = math.modf(x)
    m, ex = math.frexp(x)
    # C keeps the sign of a zero result: floor(-0.5) is -1, ceil(-0.5) is -0.0
    fl0 = float(math.floor(x)); ce0 = float(math.ceil(x))
    if fl0 == 0.0: fl0 = math.copysign(0.0, x)
    if ce0 == 0.0: ce0 = math.copysign(0.0, x)
    row = {"x": x, "floor": fl0, "ceil": ce0,
           "fabs": abs(x), "frexp_m": m, "frexp_e": ex, "modf_i": ip, "modf_f": fr}
    if x >= 0.0:
        row["sqrt"] = math.sqrt(x)
    math_rows.append(row)
pow_rows = []
for _ in range(220):
    x = rng.choice([2.0, 3.0, 10.0, 0.5, 1.5, rng.random() * 10.0, rng.random() * 1000.0 + 0.001])
    if rng.random() < 0.2:
        x = -x
    kind = rng.random()
    if kind < 0.35:
        y = float(rng.randint(-20, 20))
    elif kind < 0.5:
        y = float(rng.randint(-200, 200))
    else:
        y = rng.uniform(-12.0, 12.0)
    if x < 0.0 and y != math.floor(y):
        continue
    try:
        r = math.pow(x, y)
    except (OverflowError, ValueError):
        continue
    if r == 0.0 or abs(r) < 2.2250738585072014e-308 or abs(r) > DBL_MAX:
        continue
    pow_rows.append((x, y, r))
def bh(v):
    lo, hi = bits(v)
    return "0x%08xUL, 0x%08xUL" % (lo, hi)

with open(os.path.join(OUT, "libm.h"), "w") as f:
    f.write("/* libm.h: generated by scripts/r11c-tables.py. Do not edit. */\n")
    f.write("struct math_row { unsigned long xlo, xhi, flo, fhi, clo, chi, alo, ahi;\n")
    f.write("  int fm_e; unsigned long mlo, mhi, ilo, ihi, frlo, frhi; int has_sqrt;\n")
    f.write("  unsigned long slo, shi; };\n")
    f.write("static const struct math_row math_rows[] = {\n")
    for r in math_rows:
        has = 1 if "sqrt" in r else 0
        sq = r.get("sqrt", 0.0)
        parts = [bh(r["x"]), bh(r["floor"]), bh(r["ceil"]), bh(r["fabs"]),
                 str(r["frexp_e"]), bh(r["frexp_m"]), bh(r["modf_i"]), bh(r["modf_f"]),
                 str(has), bh(sq)]
        f.write("\t{ " + ", ".join(parts) + " },\n")
    f.write("};\n")
    f.write("#define NMATH %d\n" % len(math_rows))
    f.write("struct pow_row { unsigned long xlo, xhi, ylo, yhi, rlo, rhi; };\n")
    f.write("static const struct pow_row pow_rows[] = {\n")
    for x, y, r in pow_rows:
        f.write("\t{ " + ", ".join([bh(x), bh(y), bh(r)]) + " },\n")
    f.write("};\n")
    f.write("#define NPOW %d\n" % len(pow_rows))
print("math rows:", len(math_rows), "pow rows:", len(pow_rows))
