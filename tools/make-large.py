#!/usr/bin/env python3
"""Generate the R8 large test application (apps/large is produced from this).

Usage: make-large.py out.c expected.txt

The generated C program is about 190 KiB of text+data+BSS:
  text  : N_FUNCS small functions plus a dispatcher (~60 KiB)
  data  : a 32 KiB initialized table, value (i*7+3)&255
  BSS   : a 96 KiB zero-filled work array
The expected result of the dispatcher is computed here, with 32-bit
two's-complement wrap-around, so the guest can check that its text ran
correctly.  The constants are written to expected.txt for the reviewer.
"""
import pathlib, sys

N_FUNCS = 1400
TABLE = 32768
WORK = 98304

def wrap(v):
    return ((v + (1 << 31)) % (1 << 32)) - (1 << 31)

def consts(i):
    k1 = (i * 2654435761 + 12345) & 0x7FFFFFFF | 1
    k2 = (i * 40503 + 17) & 0x7FFFFFFF
    sh = i % 7 + 1
    return k1, k2, sh

def fn_value(x, i):
    k1, k2, sh = consts(i)
    v = wrap(wrap(x * k1) + k2)
    return wrap(v ^ (x >> sh))

def main():
    out, exp = sys.argv[1], sys.argv[2]
    lines = []
    lines.append('/* Generated by tools/make-large.py.  Do not edit. */')
    lines.append('#include "appcalls.h"')
    lines.append('')
    lines.append('static unsigned char table[%d] = {' % TABLE)
    row = []
    for i in range(TABLE):
        row.append('%d' % ((i * 7 + 3) & 255))
        if len(row) == 24:
            lines.append('\t' + ', '.join(row) + ',')
            row = []
    if row:
        lines.append('\t' + ', '.join(row) + ',')
    lines.append('};')
    lines.append('')
    lines.append('static unsigned char work[%d];' % WORK)
    lines.append('')
    for i in range(N_FUNCS):
        k1, k2, sh = consts(i)
        lines.append('static int f%d(int x) { return ((x * %dL) + %dL) ^ (x >> %d); }'
                     % (i, k1, k2, sh))
    lines.append('')
    lines.append('static int run_all(int seed)')
    lines.append('{')
    lines.append('\tint acc = seed;')
    for i in range(N_FUNCS):
        lines.append('\tacc = f%d(acc);' % i)
    lines.append('\treturn acc;')
    lines.append('}')
    lines.append('')
    lines.append('static int con;')
    lines.append('')
    lines.append('static void say(const char *s)')
    lines.append('{')
    lines.append('\tunsigned int n = 0;')
    lines.append('\twhile (s[n] != 0)')
    lines.append('\t\tn++;')
    lines.append('\tqtrap(APP_QT_CH_WRITE, (unsigned int) con, (unsigned int) s, n);')
    lines.append('}')
    lines.append('')
    lines.append('static int fail(int code)')
    lines.append('{')
    lines.append('\tsay("LARGE check failed\\n");')
    lines.append('\tqtrap(APP_QT_CH_CLOSE, (unsigned int) con, 0, 0);')
    lines.append('\treturn code;')
    lines.append('}')
    lines.append('')
    lines.append('static int streq(const char *a, const char *b)')
    lines.append('{')
    lines.append('\tint i = 0;')
    lines.append('\twhile (a[i] != 0 && a[i] == b[i])')
    lines.append('\t\ti++;')
    lines.append('\treturn a[i] == b[i];')
    lines.append('}')
    lines.append('')
    lines.append('int main(int argc, char **argv)')
    lines.append('{')
    lines.append('\tint i, r;')
    lines.append('\tunsigned int t0, t1, spin = 0, pre_free, post_free;')
    lines.append('\tchar *p;')
    lines.append('\tint ok;')
    lines.append('')
    lines.append('\tcon = qtrap(APP_QT_CH_OPEN, (unsigned int) "CON", 0, 0);')
    lines.append('\tif (con <= 0)')
    lines.append('\t\treturn 90;')
    lines.append('\t/* 1. argc and argv: RUN LARGE.AOU one "two words" */')
    lines.append('\tif (argc != 3)')
    lines.append('		return fail(10);')
    lines.append('\tif (!streq(argv[0], "LARGE.AOU") || !streq(argv[1], "one") || !streq(argv[2], "two words"))')
    lines.append('		return fail(11);')
    lines.append('\tif (argv[3] != 0)')
    lines.append('		return fail(12);')
    lines.append('\t/* 2. initialized data was copied from the file */')
    lines.append('\tfor (i = 0; i < %d; i++)' % TABLE)
    lines.append('\t\tif (table[i] != ((i * 7 + 3) & 255))')
    lines.append('\t\t\treturn fail(20);')
    lines.append('\t/* 3. BSS was zeroed by the loader, then written and read back */')
    lines.append('\tfor (i = 0; i < %d; i++)' % WORK)
    lines.append('\t\tif (work[i] != 0)')
    lines.append('\t\t\treturn fail(30);')
    lines.append('\tfor (i = 0; i < %d; i++)' % WORK)
    lines.append('\t\twork[i] = (unsigned char) ((i * 13) & 255);')
    lines.append('\tfor (i = 0; i < %d; i++)' % WORK)
    lines.append('\t\tif (work[i] != ((i * 13) & 255))')
    lines.append('\t\t\treturn fail(31);')
    lines.append('\t/* 4. text: the 1400-function dispatcher gives the expected value */')
    lines.append('\tr = run_all(1);')
    lines.append('\tif (r != %dL)' % wrap_expected())
    lines.append('		return fail(40);')
    lines.append('\t/* 5. QDOS heap: allocate, write, check, free; free bytes restored */')
    lines.append('\tpre_free = (unsigned int) qtrap(APP_QT_MEM_FREE_BYTES, 0, 0, 0);')
    lines.append('\tp = (char *) qtrap(APP_QT_MEM_ALLOC, 4096, 0, 0);')
    lines.append('\tif (p == 0 || (int) p < 0)')
    lines.append('		return fail(50);')
    lines.append('\tfor (i = 0; i < 4096; i++)')
    lines.append('\t\tp[i] = (char) (i & 127);')
    lines.append('\tfor (i = 0; i < 4096; i++)')
    lines.append('\t\tif (p[i] != (char) (i & 127))')
    lines.append('\t\t\treturn fail(51);')
    lines.append('\tif (qtrap(APP_QT_MEM_FREE, (unsigned int) p, 0, 0) != 0)')
    lines.append('		return fail(52);')
    lines.append('\tpost_free = (unsigned int) qtrap(APP_QT_MEM_FREE_BYTES, 0, 0, 0);')
    lines.append('\tif (post_free != pre_free)')
    lines.append('		return fail(53);')
    lines.append('\tif (qtrap(APP_QT_MEM_VALIDATE, 0, 0, 0) != 0)')
    lines.append('		return fail(54);')
    lines.append('\t/* 6. the timer advances while this CPU-bound loop runs */')
    lines.append('\tt0 = (unsigned int) qtrap(APP_QT_TICKS, 0, 0, 0);')
    lines.append('\tt1 = t0;')
    lines.append('\twhile (t1 == t0 && spin < 200000000u) {')
    lines.append('\t\tspin++;')
    lines.append('\t\tif ((spin & 0xFFFFu) == 0)')
    lines.append('\t\t\tt1 = (unsigned int) qtrap(APP_QT_TICKS, 0, 0, 0);')
    lines.append('\t}')
    lines.append('\tif (t1 == t0)')
    lines.append('		return fail(60);')
    lines.append('\tok = 1;')
    lines.append('\tsay("QDOS/386 R8 LARGE A.OUT + ARGV PASS\\n");')
    lines.append('\tif (qtrap(APP_QT_CH_CLOSE, (unsigned int) con, 0, 0) != 0)')
    lines.append('\t\treturn 91;')
    lines.append('\treturn ok ? 0 : 1;')
    lines.append('}')
    pathlib.Path(out).write_text('\n'.join(lines) + '\n')
    pathlib.Path(exp).write_text('run_all(1) = %d\nfunctions = %d\ntable = %d bytes\nwork = %d bytes\n'
                                 % (wrap_expected(), N_FUNCS, TABLE, WORK))

_cache = {}
def wrap_expected():
    if 'v' not in _cache:
        acc = 1
        for i in range(N_FUNCS):
            acc = fn_value(acc, i)
        _cache['v'] = acc
    return _cache['v']

if __name__ == '__main__':
    main()
