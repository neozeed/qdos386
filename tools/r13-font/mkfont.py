#!/usr/bin/env python3
"""R13: build kernel/font5x9.c from tools/r13-font/qdos5x9.txt (the original QDOS5x9 fallback font) and optionally a PNG
specimen.  usage: mkfont.py SRC.txt OUT.c [SPECIMEN.png]
Encoding: codes 0x20..0x7F, 9 bytes per glyph, one byte per row, bit 7 = leftmost of the 5 columns (bits 2..0 are 0).
Code 0x7F is the "missing" glyph, shown for every code outside 0x20..0x7E."""
import hashlib, sys

src, out = sys.argv[1], sys.argv[2]
glyphs, cur, code = {}, None, None
for ln, line in enumerate(open(src, encoding="ascii"), 1):
    line = line.rstrip("\n")
    if not line or line.startswith(";"):
        continue
    if line.startswith("= "):
        code = int(line[2:], 16)
        assert code not in glyphs, "duplicate glyph %02X (line %d)" % (code, ln)
        glyphs[code] = cur = []
        continue
    assert len(line) == 5 and set(line) <= set("#."), "bad row at line %d: %r" % (ln, line)
    cur.append(line)
assert sorted(glyphs) == list(range(0x20, 0x80)), "codes 20..7F must all be present"
for c, rows in glyphs.items():
    assert len(rows) == 9, "glyph %02X has %d rows" % (c, len(rows))
data = []
for c in range(0x20, 0x80):
    data.append([sum(0x80 >> i for i, ch in enumerate(r) if ch == "#") for r in glyphs[c]])
blob = bytes(b for g in data for b in g)
h = hashlib.sha256(blob).hexdigest()
with open(out, "w") as f:
    f.write("/* QDOS/386 R13 - the QDOS5x9 fallback font (original glyphs, tools/r13-font/qdos5x9.txt; generated by\n"
            " * tools/r13-font/mkfont.py - do not edit).  Codes 0x20..0x7F, 9 rows of 5 pixels, bit 7 = leftmost pixel;\n"
            " * 0x7F is the missing-glyph box.  SHA-256 of the 864 bytes: %s */\n" % h)
    f.write('#include "font.h"\n\nconst unsigned char font5x9[96][9] = {\n')
    for i, g in enumerate(data):
        f.write("\t{ %s },   /* %02X %s */\n" % (", ".join("0x%02x" % b for b in g), 0x20 + i,
                repr(chr(0x20 + i)) if 0x20 + i < 0x7F else "missing"))
    f.write("};\n")
print("font5x9: 96 glyphs, %d bytes, sha256 %s" % (len(blob), h))
if len(sys.argv) > 3:
    from PIL import Image
    S, cw, ch = 4, 6, 10
    img = Image.new("RGB", (16 * cw * S, 6 * ch * S), (0, 0, 96))
    px = img.load()
    for i, g in enumerate(data):
        ox, oy = (i % 16) * cw * S, (i // 16) * ch * S
        for y, row in enumerate(g):
            for x in range(5):
                if row & (0x80 >> x):
                    for a in range(S):
                        for b in range(S):
                            px[ox + x * S + a, oy + y * S + b] = (255, 255, 200)
    img.save(sys.argv[3])
