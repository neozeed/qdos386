#!/usr/bin/env python3
"""R13: extract the two QL character-set fonts of Minerva 1.98 (tb_f0: codes $1F..$7F, tb_f1: codes $80 up) and
generate kernel/font_minerva.c.  Minerva 1.98 is GPL-2.0 (Laurence Reeves; github.com/MarcelKilgus/Minerva); see
docs/R13-FONT-PROVENANCE.md.
  usage: minerva-font.py ROM.rom|- TB_F0.s TB_F1.s OUT.c [SPECIMEN.png]      ("-": source only, no ROM cross-check)
The font is read from BOTH inputs and they must agree byte for byte: the GAS source modules tb_f0.s/tb_f1.s (the
"/* QL: dc.b O.O.. */" pixel rows of the original source, kept as comments) and the 48,822-byte ROM (located by
searching for the header + all rows).  QL font layout: byte 0 = first code, byte 1 = number of glyphs - 1, then 9
bytes per glyph, one per row, pixels in bits 6..2 (bit 6 = leftmost).  A code outside a font's range shows the font's
first glyph (Minerva cs_char).  Output rows use bit 7 = leftmost (the QDOS/386 font.h layout): row << 1."""
import hashlib, re, sys

ROM_SHA = "aafbd3b0b2bf60d2cdeb139a355d552908b041ab021a1ff1b0be5547d9bcf2a2"
rom_p, f0_p, f1_p, out = sys.argv[1:5]
rom = open(rom_p, "rb").read() if rom_p != "-" else None
assert rom is None or hashlib.sha256(rom).hexdigest() == ROM_SHA, "not the Minerva 1.98 ROM (sha256 %s)" % hashlib.sha256(rom).hexdigest()


def parse(path):
    first, rows = None, []
    for line in open(path, encoding="latin-1"):
        m = re.match(r"^/\* QL:\s+dc\.b\s+(\S+)", line)
        if not m:
            continue
        t = m.group(1)
        if first is None:
            first = int(re.match(r"^\$([0-9a-fA-F]+),", t).group(1), 16)
            continue
        assert re.match(r"^[O.]{5}$", t), "%s: unexpected row %r" % (path, t)
        rows.append(sum(0x40 >> i for i, ch in enumerate(t) if ch == "O"))
    assert first is not None and len(rows) % 9 == 0, path
    return first, rows


fonts = []
for p in (f0_p, f1_p):
    first, rows = parse(p)
    n = len(rows) // 9
    blob = bytes([first, n - 1] + rows)
    if rom is None:
        fonts.append((first, n, rows, None))
        print("%s: codes $%02X..$%02X (%d glyphs), source only" % (p.split("/")[-1], first, first + n - 1, n))
        continue
    at = [m.start() for m in re.finditer(re.escape(blob), rom)]
    assert len(at) == 1, "%s: found %d times in the ROM" % (p, len(at))
    fonts.append((first, n, rows, at[0]))
    print("%s: codes $%02X..$%02X (%d glyphs), ROM offset 0x%04X, source and ROM agree" % (p.split("/")[-1], first, first + n - 1, n, at[0]))

(f0, n0, r0, a0), (f1, n1, r1, a1) = fonts


def glyph(code):
    """Minerva's choice for one byte code: font 0 if in its range, else font 1 if in its range, else font 0's
    first glyph (the 'invalid character' pattern)."""
    if f0 <= code < f0 + n0:
        r, i = r0, code - f0
    elif f1 <= code < f1 + n1:
        r, i = r1, code - f1
    else:
        r, i = r0, 0
    return [(b << 1) & 0xff for b in r[9 * i:9 * i + 9]]


table = [glyph(c) for c in range(256)]
blob = bytes(b for g in table for b in g)
h = hashlib.sha256(blob).hexdigest()
with open(out, "w") as f:
    f.write("/* QDOS/386 R13 - the Minerva 1.98 QL fonts (tb_f0 $%02X..$%02X, tb_f1 $%02X..$%02X) as one 256-code table.\n"
            " * Generated by tools/r13-font/minerva-font.py from the GAS source modules third_party/minerva/src/tb_f0.s and\n"
            " * tb_f1.s, cross-checked byte for byte against min198.rom (sha256 %s) - do not edit.\n"
            " * Minerva is Copyright Laurence Reeves and contributors, distributed under the GNU General Public License,\n"
            " * version 2 (see docs/R13-FONT-PROVENANCE.md and third_party/minerva/COPYING).  9 rows of 5 pixels per code,\n"
            " * bit 7 = leftmost pixel; codes outside both fonts show tb_f0's first glyph, as Minerva does.\n"
            " * QL character set, not CP437: $60 is the pound sign, $7F the copyright sign, $80.. accented letters.\n"
            " * SHA-256 of the 2304 bytes: %s */\n" % (f0, f0 + n0 - 1, f1, f1 + n1 - 1, ROM_SHA, h))
    f.write('#include "font.h"\n\nconst unsigned char font_minerva[256][9] = {\n')
    for c, g in enumerate(table):
        f.write("\t{ %s },   /* %02X */\n" % (", ".join("0x%02x" % b for b in g), c))
    f.write("};\n")
print("font_minerva: 256 codes, sha256 %s" % h)
if len(sys.argv) > 5:
    from PIL import Image
    S, cw, ch = 4, 6, 10
    img = Image.new("RGB", (16 * cw * S, 16 * ch * S), (0, 0, 96))
    px = img.load()
    for i, g in enumerate(table):
        ox, oy = (i % 16) * cw * S, (i // 16) * ch * S
        for y, row in enumerate(g):
            for x in range(6):
                if row & (0x80 >> x):
                    for a in range(S):
                        for b in range(S):
                            px[ox + x * S + a, oy + y * S + b] = (255, 255, 200)
    img.save(sys.argv[5])
