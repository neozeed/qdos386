#!/bin/sh
# R11L: stage the historical sources for the guest port.  Copies gcc-1.40, gas-1.38, binutils-1.94 and
# bison-1.16 from $QDOS386_TOOLS (the user's working legacy tree) into build/r11l/src, converting CR LF to LF in
# text sources (GCC 1.40's own cpp treats a CR as garbage).  Original hashes are recorded in
# build/r11l/src/ORIGINAL.SHA256 so the staged copy can always be traced to the unmodified file.
#   usage: sh tools/r11l-stage-src.sh
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd); cd "$ROOT"
T=${QDOS386_TOOLS:?set QDOS386_TOOLS}
D=build/r11l/src; rm -rf "$D"; mkdir -p "$D"
for d in gcc-1.40 gas-1.38 binutils-1.94 bison-1.16; do
	( cd "$T" && find "$d" -type f ! -name '*.exe' ! -name '*.obj' ! -name '*.o' ! -name '*.dvi' ! -name '*.zip' ) | LC_ALL=C sort > "$D/.list.$d"
	while read f; do
		mkdir -p "$D/$(dirname "$f")"
		# text (no NUL byte) loses its CRs; everything else is copied byte for byte
		if grep -qI . "$T/$f" 2>/dev/null; then tr -d '\r' < "$T/$f" > "$D/$f"; else cp "$T/$f" "$D/$f"; fi
	done < "$D/.list.$d"
done
( cd "$T" && for d in gcc-1.40 gas-1.38 binutils-1.94 bison-1.16; do sed "s#^#$T/#" "$ROOT/$D/.list.$d"; done | xargs sha256sum | sed "s#$T/##" ) > "$D/ORIGINAL.SHA256"
# an untouched LF copy for the HOST bootstrap (gen* programs, bison); the guest copy below gets the overlay
rm -rf "$D-host"; mkdir -p "$D-host"; rm -f "$D"/.list.*; cp -R "$D"/. "$D-host"/
# R11L patches (the only guest-specific edits to the legacy sources; generated by tools/r11l-mkpatch.sh)
for p in port/patches/*.patch; do [ -f "$p" ] && patch -s -p1 -d "$D" < "$p"; done
rm -f "$D"/.list.*
echo "staged $(find $D -type f | wc -l) files; $(wc -l < $D/ORIGINAL.SHA256) original hashes"
