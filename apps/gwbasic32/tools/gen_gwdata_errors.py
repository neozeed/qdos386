#!/usr/bin/env python3
"""Generate src/gwdata_errors.inc from the ERRTAB..LSTERR region of GWDATA.ASM.

Macro semantics (OEM.H / GWDATA.ASM):
  DCE X   : empty macro (the two-letter error code is not emitted)
  DCL X   : QQ=QQ+1; DC X (characters of X, quotes dropped); DB 0
  DC X    : one DB per character of X, quote characters dropped
  NAME=QQ : error number (absolute symbol)
  QQ=n    : sets the counter
Labels and PUBLIC lines are carried over. "$" in names becomes "_".
"""
import re, sys

SRC, OUT = sys.argv[1], sys.argv[2]
lines = open(SRC, 'rb').read().decode('latin-1').replace('\r', '').split('\n')

start = next(i for i, l in enumerate(lines) if l.startswith('ERRTAB:'))
end = next(i for i, l in enumerate(lines) if re.match(r'\s*LSTERR=QQ\+1', l))

sym = {}
QQ = [0]
out = ['# GWDATA.ASM ERRTAB..LSTERR -> gwdata_errors.inc (generated by tools/gen_gwdata_errors.py)',
       '# Error message table: each message is followed by a zero byte. Error numbers are the',
       '# 1-based message indexes, as in the original.']

def g(n):
    return n.replace('$', '_').replace('?', 'Q_')

def ev(e):
    e = e.strip()
    e = re.sub(r'\bOFFSET\s+', '', e)
    e = re.sub(r'\b([0-9]+)D\b', lambda m: m.group(1), e)
    e = re.sub(r'\b([0-7]+)O\b', lambda m: str(int(m.group(1), 8)), e)
    e = re.sub(r'\$', '(HERE)', e)
    def rs(m):
        n = m.group(0)
        if n == 'QQ':
            return '(%d)' % QQ[0]
        if n == '(HERE)':
            return n
        if n in sym:
            return '(%d)' % sym[n]
        raise KeyError('undefined in ERRTAB expr: ' + n + ' in ' + e)
    e = re.sub(r'\(HERE\)|[A-Za-z_][A-Za-z0-9_$]*', rs, e)
    return eval(e, {'__builtins__': {}}, {'HERE': 0})

in_macro = False
for raw in lines[start:end + 1]:
    l = raw.split(';', 1)[0].strip()
    if not l:
        continue
    if re.search(r'\bMACRO\b', l):
        in_macro = True
        continue
    if in_macro:
        if l == 'ENDM':
            in_macro = False
        continue
    if l.startswith('ERRTAB:'):
        out.append('ERRTAB:')
        QQ[0] = 0
        continue
    m = re.match(r'^(DCE)\s+(".*")', l)
    if m:
        continue
    if re.match(r'^DB\s+0$', l):
        out.append('\t.byte 0')
        continue
    m = re.match(r'^DCL\s+"(.*)"$', l)
    if m:
        QQ[0] += 1
        out.append('\t.ascii "%s"' % m.group(1))
        out.append('\t.byte 0')
        continue
    m = re.match(r'^PUBLIC\s+(.*)$', l)
    if m:
        for n in m.group(1).split(','):
            out.append('\t.globl ' + g(n.strip()))
        continue
    m = re.match(r'^([$A-Za-z_][$A-Za-z0-9_]*):\s*$', l)
    if m:
        out.append(g(m.group(1)) + ':')
        continue
    m = re.match(r'^([$A-Za-z_][$A-Za-z0-9_]*)\s+LABEL', l)
    if m:
        out.append(g(m.group(1)) + ':')
        continue
    m = re.match(r'^QQ\s*=\s*(.+)$', l)
    if m:
        QQ[0] = ev(m.group(1))
        continue
    m = re.match(r'^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.+)$', l)
    if m:
        name, expr = m.group(1), m.group(2)
        if '$' in expr:
            # location-counter expression, e.g. DSKLOC=$+6: base label plus offset
            base = '_LOC_' + g(name)
            out.append(base + ':')
            off = re.sub(r'\$', '0', expr)
            off = ev(off)
            sym[name] = QQ[0]  # placeholder, replaced below
            out.append('\t.set %s, %s + %d' % (g(name), base, off))
            continue
        if name == 'DSKLOC':
            continue
        v = ev(expr)
        sym[name] = v
        out.append('\t.set %s, %d' % (g(name), v))
        continue
    raise SystemExit('UNHANDLED ERRTAB LINE: %r' % raw)

# Error number equates: NAME=QQ inside DCL sections are written as ".set NAME, QQ"
# (the regex above handles them via the symbol path with QQ substituted).
open(OUT, 'w').write('\n'.join(out) + '\n')
print('wrote', OUT, 'messages', sum(1 for x in out if x.startswith('\t.ascii')), 'symbols', len(sym))
