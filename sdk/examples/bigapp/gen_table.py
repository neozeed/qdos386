#!/usr/bin/env python3
"""Generate the initialized table for BIGAPP.AOU (an R9 slot-1 image).

usage: gen_table.py > table.c

The table is 65536 bytes of initialized data, table[i] = (i*7 + 3) & 255, so the
program can check the data path exactly without storing a copy of it in source.
"""
import sys

N = 65536
out = sys.stdout
out.write('/* generated by gen_table.py: table[i] = (i*7 + 3) & 255 */\n')
out.write('unsigned char table[%d] = {\n' % N)
row = []
for i in range(N):
    row.append('%d' % ((i * 7 + 3) & 255))
    if len(row) == 24:
        out.write('\t' + ','.join(row) + ',\n')
        row = []
if row:
    out.write('\t' + ','.join(row) + '\n')
out.write('};\n')
